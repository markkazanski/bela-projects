#!/usr/bin/env python3
"""Generate Patterns.h from Mutable Instruments Grids resources.cc (GPLv3)."""
from __future__ import annotations

import re
import sys
import urllib.request
from pathlib import Path

RESOURCES_URL = (
    "https://raw.githubusercontent.com/pichenettes/eurorack/master/grids/resources.cc"
)
PATTERN_GEN_URL = (
    "https://raw.githubusercontent.com/pichenettes/eurorack/master/grids/pattern_generator.cc"
)
NODE_BYTES = 96  # 3 instruments * 32 steps
OUT = Path(__file__).resolve().parent.parent / "project" / "Patterns.h"


def fetch(url: str) -> str:
    with urllib.request.urlopen(url, timeout=60) as r:
        return r.read().decode("utf-8")


def parse_nodes(resources: str) -> dict[int, list[int]]:
    nodes: dict[int, list[int]] = {}
    pat = re.compile(
        r"const prog_uint8_t node_(\d+)\[\] PROGMEM = \{\s*(.*?)\s*\};",
        re.DOTALL,
    )
    for m in pat.finditer(resources):
        idx = int(m.group(1))
        body = m.group(2)
        vals = [int(x) for x in re.findall(r"\d+", body)]
        if len(vals) != NODE_BYTES:
            raise SystemExit(f"node_{idx}: expected {NODE_BYTES} bytes, got {len(vals)}")
        nodes[idx] = vals
    if len(nodes) != 25:
        raise SystemExit(f"expected 25 nodes, found {len(nodes)}")
    return nodes


def parse_drum_map(pg: str) -> list[list[int]]:
    block = re.search(r"static const prog_uint8_t\* drum_map\[5\]\[5\] = \{(.*?)\};", pg, re.DOTALL)
    if not block:
        raise SystemExit("drum_map not found")
    rows = []
    for line in block.group(1).split("\n"):
        line = line.strip().rstrip(",")
        if not line.startswith("{"):
            continue
        refs = re.findall(r"node_(\d+)", line)
        if len(refs) != 5:
            raise SystemExit(f"bad drum_map row: {line}")
        rows.append([int(x) for x in refs])
    if len(rows) != 5:
        raise SystemExit(f"expected 5 drum_map rows, got {len(rows)}")
    return rows


def emit(nodes: dict[int, list[int]], drum_map: list[list[int]]) -> str:
    lines = [
        "// Auto-generated by tools/gen_patterns.py from Grids resources.cc (GPLv3).",
        "// Do not edit.",
        "#pragma once",
        "#include <cstdint>",
        "",
        "namespace Patterns {",
        "",
        "constexpr int kGridSize = 5;",
        "constexpr int kSteps = 32;",
        "constexpr int kParts = 3;",
        "constexpr int kNodeBytes = 96;",
        "",
    ]
    for n in range(25):
        vals = nodes[n]
        chunk = ", ".join(str(v) for v in vals)
        lines.append(f"constexpr uint8_t kNode{n}[kNodeBytes] = {{ {chunk} }};")
        lines.append("")
    lines.append("constexpr uint8_t kDrumMap[kGridSize][kGridSize] = {")
    for row in drum_map:
        cells = ", ".join(str(i) for i in row)
        lines.append(f"    {{ {cells} }},")
    lines.append("};")
    lines.append("")
    lines.append("inline const uint8_t* nodeData(int id) {")
    lines.append("    static const uint8_t* const table[25] = {")
    for n in range(25):
        lines.append(f"        kNode{n},")
    lines.append("    };")
    lines.append("    if (id < 0 || id >= 25) return kNode0;")
    lines.append("    return table[id];")
    lines.append("}")
    lines.append("")
    lines.append("} // namespace Patterns")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    resources = fetch(RESOURCES_URL)
    pg = fetch(PATTERN_GEN_URL)
    nodes = parse_nodes(resources)
    drum_map = parse_drum_map(pg)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(emit(nodes, drum_map))
    print(f"Wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
